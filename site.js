const aliases = { "fr-FR": "fr", "en-US": "en", "ja-JP": "ja", "zh-CN": "zh", "zh-Hans": "zh", "es-ES": "es", "de-DE": "de" };
const params = new URLSearchParams(location.search);
const requested = params.get("lang") || navigator.language || "en";
let language = aliases[requested] || aliases[requested.replace("_", "-")] || requested.slice(0, 2);
if (!COPY[language]) language = "en";

function applyLanguage(code) {
  const copy = COPY[code] || COPY.en;
  document.documentElement.lang = copy.lang;
  document.title = copy.title;
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const value = copy[element.dataset.i18n];
    if (value) element.textContent = value;
  });
  document.querySelectorAll("[data-lang-link]").forEach((link) => {
    const target = new URL(link.getAttribute("href"), location.href);
    target.searchParams.set("lang", code);
    link.href = target.pathname + target.search;
  });
  const picker = document.querySelector("#language");
  if (picker) picker.value = code;
}

document.addEventListener("DOMContentLoaded", () => {
  applyLanguage(language);
  const picker = document.querySelector("#language");
  if (picker) picker.addEventListener("change", () => {
    language = picker.value;
    const url = new URL(location.href);
    url.searchParams.set("lang", language);
    history.replaceState({}, "", url);
    applyLanguage(language);
  });
});
